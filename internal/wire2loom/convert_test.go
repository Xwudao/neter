func TestMatchesConstructor(t *testing.T) {
	// The entry is found from the bound type, in either spelling.
	assert.True(t, matchesConstructor("NewLogBroadcaster", "LogBroadcaster"))
	assert.True(t, matchesConstructor("logger.NewLogBroadcaster", "LogBroadcaster"))
	assert.True(t, matchesConstructor("NewStore", "store"))
	assert.True(t, matchesConstructor("newStore", "store"))
	assert.False(t, matchesConstructor("NewLogBroadcaster", "Logger"))
	assert.False(t, matchesConstructor("ProvideStore", "Store"))
}

