func TestIsModuleReference(t *testing.T) {
	registry := map[string]*setModel{
		"ProviderBizSet":    {},
		"ProviderConfigSet": {},
		"ProvideUtilSet":    {},
	}
	assert.True(t, isModuleReference("ProviderBizSet", registry))
	assert.True(t, isModuleReference("config.ProviderConfigSet", registry))
	// ProvideUtilSet is a set even though its name starts with "Provide".
	assert.True(t, isModuleReference("utils.ProvideUtilSet", registry))
	// ProvideStorageConfigLoader is a constructor despite its prefix.
	assert.False(t, isModuleReference("ProvideStorageConfigLoader", registry))
	assert.False(t, isModuleReference("NewUserBiz", registry))
	assert.False(t, isModuleReference("ai.NewOpenAICompat", registry))
	// A set from another module is still recognised by its name.
	assert.True(t, isModuleReference("shared.HTTPSet", registry))
}
